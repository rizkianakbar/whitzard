// Writes typed ABIs (`as const`, for viem/wagmi type inference) from the Hardhat build output.
// Run after any contract change:  (cd ../blockchain && pnpm hardhat build) && node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifacts = join(here, "../../blockchain/artifacts/contracts");
const out = join(here, "../src/lib/abi");

const contracts = [
  ["WhitzardToken.sol/WhitzardToken.json", "tokenAbi", "token.ts"],
  ["Registry.sol/Registry.json", "registryAbi", "registry.ts"],
  ["Escrow.sol/Escrow.json", "escrowAbi", "escrow.ts"],
];

for (const [artifact, name, file] of contracts) {
  const { abi } = JSON.parse(readFileSync(join(artifacts, artifact), "utf8"));
  const source = `// Generated by scripts/gen-abi.mjs from ${artifact}. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(out, file), source);
  console.log(`wrote src/lib/abi/${file}`);
}
